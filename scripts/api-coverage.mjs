import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => readFileSync(resolve(root, path), 'utf8');
const sha = value => createHash('sha256').update(value).digest('hex');
const contractText = read('docs/openapi.json');
const contract = JSON.parse(contractText);
const map = JSON.parse(read('reports/api/coverage-map.json'));
const methods = new Set(['get', 'put', 'post', 'delete', 'patch', 'head', 'options', 'trace']);
const operations = Object.entries(contract.paths).flatMap(([path, item]) => Object.entries(item)
  .filter(([method]) => methods.has(method)).map(([method, operation]) => ({ key: `${method.toUpperCase()} ${path}`, operation })))
  .sort((a, b) => a.key.localeCompare(b.key));
const keys = new Set(operations.map(row => row.key));
for (const [key, entry] of Object.entries(map.operations)) {
  if (!keys.has(key)) throw new Error(`Operation removed or renamed in OpenAPI: ${key}`);
  if (!entry.assertedStatuses.length || !entry.assertedStatuses.every(s => Number.isInteger(s) && s >= 100 && s <= 599)) throw new Error(`Invalid status mapping: ${key}`);
  if (sha(read(entry.spec)) !== entry.reviewedSha256) throw new Error(`Re-review target assertions and update mapping/hash for ${entry.spec}; do not count setup/cleanup requests.`);
}
const specs = readdirSync(resolve(root, 'tests/api'), { recursive: true }).filter(f => f.endsWith('.spec.ts')).map(f => `tests/api/${f}`);
for (const spec of specs) if (!Object.values(map.operations).some(entry => entry.spec === spec)) throw new Error(`Unmapped API spec: ${spec}`);
const percent = (n, d) => `${(100 * n / d).toFixed(1)}%`;
const covered = operations.filter(row => map.operations[row.key]);
let responseTotal = 0, responseCovered = 0;
const rows = operations.map(({ key, operation }) => {
  const entry = map.operations[key];
  const statuses = Object.keys(operation.responses).sort();
  responseTotal += statuses.length;
  responseCovered += statuses.filter(s => entry?.assertedStatuses.includes(Number(s))).length;
  const missing = statuses.filter(s => !entry?.assertedStatuses.includes(Number(s)));
  return `| \`${key}\` | ${entry ? `[${entry.spec.replace('tests/api/', '')}](../../${entry.spec})` : 'Not automated'} | ${statuses.join(', ')} | ${entry?.assertedStatuses.join(', ') ?? '—'} | ${missing.join(', ') || '—'} |`;
});
const output = `# API coverage inventory\n\nGenerated from OpenAPI and the reviewed [mapping](coverage-map.json). Run \`npm run coverage:api\`; do not edit this file manually.\n\n- Reviewed: ${map.reviewedOn}. Contract version: ${contract.info.version}.\n- Contract SHA-256: \`${sha(contractText)}\`.\n- Endpoint breadth: **${covered.length}/${operations.length} = ${percent(covered.length, operations.length)}**. Remaining: **${operations.length-covered.length}**.\n- Documented operation/status pairs with assertions: **${responseCovered}/${responseTotal} = ${percent(responseCovered, responseTotal)}**.\n- These are implementation inventory metrics, not pass rates, code coverage, schema completeness, or complete behavior coverage. Fixture/cleanup calls do not count. Undocumented asserted statuses appear below but do not inflate the documented-status numerator.\n- Current-run health: not measured by this generator. Record actual execution separately in [the plan](test-plan.md).\n\n| Operation | Dedicated spec | Documented statuses | Reviewed target statuses | Missing documented statuses |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`;
const destination = 'reports/api/coverage.md';
if (process.argv.includes('--check')) {
  if (read(destination) !== output) throw new Error('Coverage inventory is stale: npm run coverage:api');
  console.log(`Coverage current: ${covered.length}/${operations.length} (${percent(covered.length, operations.length)}); ${responseCovered}/${responseTotal} documented status pairs.`);
} else {
  writeFileSync(resolve(root, destination), output);
  console.log(`Updated ${destination}: ${covered.length}/${operations.length} (${percent(covered.length, operations.length)}).`);
}
